<?php

    // while loop 
    $number = 10;
    while($number >= 1)
    {
        echo $number;
        echo "<br>";
        $number--;
    }

    // do..while loop
    $number = 1;
    echo "<br>";
    do{
        echo $number;
        echo "<br>";
        $number++;  
    } while($number <= 10)

?>